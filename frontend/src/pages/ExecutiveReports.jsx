import { useCallback, useEffect, useState } from 'react';
import api from '../services/api';
import { useBusy } from '../context/BusyContext';
import { useWorkspaces } from '../context/WorkspaceContext';
import {
  Alert,
  Badge,
  Button,
  Card,
  CardBody,
  CardHeader,
  EmptyState,
  Hint,
  Input,
  Menu,
  PageHeader,
  Section,
  Segmented,
  Select,
  SkeletonPage,
  Stat,
  StatGrid,
  Toolbar,
  ToolbarField,
} from '../components/ui';

/**
 * Reports — executive summaries, product strategy and the quality evaluation.
 *
 * A report here is an argument built from measurements, so the page leads with the
 * measured health snapshot and keeps the provenance block visible at the bottom.
 * The quality evaluation sits on the same page because the two belong together: a
 * reader should be able to check the report's own grounding before quoting it.
 */

const REPORT_TYPES = [
  { value: 'executive_summary', label: 'Executive summary' },
  { value: 'product_strategy', label: 'Product strategy' },
];

const AUDIENCES = [
  { value: 'executive_leadership', label: 'Executive leadership' },
  { value: 'product_team', label: 'Product team' },
  { value: 'engineering_leadership', label: 'Engineering leadership' },
  { value: 'stakeholders', label: 'Stakeholders & sponsors' },
];

const SEVERITY_TONES = { high: 'danger', medium: 'warning', low: 'neutral' };
const CHECK_TONES = { pass: 'success', warn: 'warning', fail: 'danger' };
const GRADE_TONES = {
  excellent: 'success',
  good: 'success',
  fair: 'warning',
  needs_review: 'danger',
  not_generated: 'neutral',
};

const formatDate = (value) => {
  if (!value) return '—';
  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) return value;
  return parsed.toLocaleString(undefined, {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
};

const downloadMarkdown = async (path, fallbackName, onNotice) => {
  const { data } = await api.get(path);
  const blob = new Blob([typeof data === 'string' ? data : JSON.stringify(data, null, 2)], {
    type: 'text/markdown',
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fallbackName;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
  onNotice?.();
};

export default function ExecutiveReports() {
  const { begin } = useBusy();
  const { activeId: workspaceId, activeWorkspace, ready } = useWorkspaces();

  const [reports, setReports] = useState(() => (workspaceId ? api.getCached(`/reports/workspace/${workspaceId}`) || [] : []));
  const [selectedId, setSelectedId] = useState(() => (workspaceId ? api.getCached(`/reports/workspace/${workspaceId}`)?.[0]?.id || '' : ''));
  const [quality, setQuality] = useState(null);
  const [loading, setLoading] = useState(() => !workspaceId || !api.getCached(`/reports/workspace/${workspaceId}`));
  const [generating, setGenerating] = useState(false);
  const [evaluating, setEvaluating] = useState(false);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');

  const [reportType, setReportType] = useState('executive_summary');
  const [audience, setAudience] = useState('executive_leadership');
  const [period, setPeriod] = useState('');
  const [focus, setFocus] = useState('');
  // The settings are a means to the report, not the report. They start closed
  // once there is something to read, and open by themselves when there isn't.
  const [showSettings, setShowSettings] = useState(false);

  const loadReports = useCallback(async (id) => {
    if (!id) return;
    if (!api.getCached(`/reports/workspace/${id}`)) {
      setLoading(true);
    }
    setError('');
    setQuality(null);
    try {
      const { data } = await api.get(`/reports/workspace/${id}`);
      setReports(data || []);
      setSelectedId((curr) => curr || data?.[0]?.id || '');
    } catch {
      setError('Could not load reports for this workspace.');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    if (workspaceId) loadReports(workspaceId);
  }, [workspaceId, loadReports]);

  const selected = reports.find((report) => report.id === selectedId) || null;

  const generate = async () => {
    if (!workspaceId) return;
    setGenerating(true);
    setError('');
    setNotice('');
    const done = begin('Writing the report…');
    try {
      const { data } = await api.post('/reports/generate', {
        workspace_id: workspaceId,
        report_type: reportType,
        audience,
        period: period.trim() || null,
        focus: focus.trim() || null,
      });
      setReports((current) => [data, ...current]);
      setSelectedId(data.id);
      setNotice(`Report generated by ${data.ai_model}.`);
    } catch (err) {
      setError(err?.response?.data?.detail || 'Could not generate the report.');
    } finally {
      setGenerating(false);
      done();
    }
  };

  const evaluate = async () => {
    if (!workspaceId) return;
    setEvaluating(true);
    setError('');
    const done = begin('Evaluating output quality…');
    try {
      const { data } = await api.get(`/quality/${workspaceId}/evaluate`);
      setQuality(data);
    } catch (err) {
      setError(err?.response?.data?.detail || 'Could not evaluate the generated outputs.');
    } finally {
      setEvaluating(false);
      done();
    }
  };

  return (
    <div className="page-container stack stack-lg">
      <PageHeader
        icon="file"
        title="Reports"
        trail="measured"
        description={
          activeWorkspace
            ? `Executive summaries, strategy and output-quality evidence for ${activeWorkspace.name}.`
            : 'Generate an executive summary or product strategy report from measured workspace evidence.'
        }
        actions={
          <>
            {selected && (
              <Menu
                label="Download"
                icon="download"
                items={[
                  {
                    label: 'Markdown (.md)',
                    icon: 'file',
                    onSelect: () =>
                      downloadMarkdown(
                        `/reports/${selected.id}/export`,
                        `report-${selected.report_type}.md`,
                        () => setNotice('Report exported as Markdown.')
                      ),
                  },
                  { label: 'Print / PDF', icon: 'clipboard', onSelect: () => window.print() },
                ]}
              />
            )}
            <Button
              variant="primary"
              icon="sparkle"
              onClick={generate}
              disabled={!ready || !workspaceId || generating}
            >
              Generate report
            </Button>
          </>
        }
      />

      {error && <Alert variant="danger" title="Something went wrong">{error}</Alert>}
      {notice && <Alert variant="success" title="Done">{notice}</Alert>}

      {loading && <SkeletonPage />}

      {/* Settings live below the report they configure, collapsed by default,
          and open themselves when there is no report to read yet. */}
      <Card flush>
        <CardHeader
          title="Report settings"
          hint="Type, audience and period change the framing — never the numbers."
          actions={
            <Button
              variant="ghost"
              size="sm"
              icon={showSettings ? 'chevronUp' : 'sliders'}
              aria-expanded={showSettings}
              onClick={() => setShowSettings((value) => !value)}
            >
              {showSettings ? 'Hide' : 'Adjust'}
            </Button>
          }
        />
        {(showSettings || !selected) && (
        <CardBody className="stack stack-md">
          <Segmented label="Report type" options={REPORT_TYPES} value={reportType} onChange={setReportType} />
          <Toolbar
            left={
              <>
                <ToolbarField label="Audience" htmlFor="report-audience">
                  <Select
                    id="report-audience"
                    value={audience}
                    onChange={(event) => setAudience(event.target.value)}
                  >
                    {AUDIENCES.map((option) => (
                      <option key={option.value} value={option.value}>
                        {option.label}
                      </option>
                    ))}
                  </Select>
                </ToolbarField>
                <ToolbarField label="Period (optional)" htmlFor="report-period">
                  <Input
                    id="report-period"
                    type="text"
                    placeholder="e.g. Q4 2026"
                    value={period}
                    onChange={(event) => setPeriod(event.target.value)}
                  />
                </ToolbarField>
                <ToolbarField label="Focus (optional)" htmlFor="report-focus">
                  <Input
                    id="report-focus"
                    type="text"
                    placeholder="e.g. churn before acquisition"
                    value={focus}
                    onChange={(event) => setFocus(event.target.value)}
                  />
                </ToolbarField>
              </>
            }
          />
        </CardBody>
        )}
      </Card>

      {!loading && !reports.length && (
        <EmptyState
          icon="file"
          title="No reports yet"
          actions={
            <Button icon="sparkle" onClick={generate} disabled={generating}>
              Generate the first report
            </Button>
          }
        >
          <p>
            An executive summary states the product’s measured health, the problems behind it and what the plan
            does about them. A strategy report adds the pillars, the roadmap outlook and the risks. Both cite only
            figures this workspace has actually measured.
          </p>
        </EmptyState>
      )}

      {!loading && reports.length > 0 && (
        <Section title="Saved reports" hint={`${reports.length} in this workspace`}>
          {/* A list, not a row of identical tabs: which report this is, what
              kind it is, and when it was written, in that order. */}
          <ul className="report-list">
            {reports.map((report) => {
              const kind = report.report_type === 'product_strategy' ? 'Strategy' : 'Executive summary';
              const isActive = report.id === selectedId;
              return (
                <li key={report.id}>
                  <button
                    type="button"
                    className={`card card-interactive report-list-item${isActive ? ' is-active' : ''}`}
                    aria-current={isActive}
                    onClick={() => setSelectedId(report.id)}
                  >
                    <span className="report-item-top">
                      <strong>{report.period ? `${report.period} ${kind}` : kind}</strong>
                      <span className="report-item-kind">{kind}</span>
                    </span>
                    <span className="report-item-title">{report.title}</span>
                    <span className="report-item-meta">
                      <span>{formatDate(report.created_at)}</span>
                      <span>
                        {report.audience?.replace(/_/g, ' ') || 'executive leadership'}
                      </span>
                    </span>
                  </button>
                </li>
              );
            })}
          </ul>
        </Section>
      )}

      {selected && (
        <>
          <Card>
            <CardHeader
              title={selected.title}
              hint={`${
                selected.report_type === 'product_strategy' ? 'Product strategy' : 'Executive summary'
              } · for ${selected.audience?.replace(/_/g, ' ') || 'executive leadership'}`}
              actions={
                <Hint label="How this report was written">
                  {selected.ai_generated
                    ? `Written by ${selected.ai_model}`
                    : 'Written deterministically, with no model involved'}
                  . Every figure comes from this workspace’s records, and the evidence block below
                  lists them.
                </Hint>
              }
            />
            <CardBody className="stack stack-md">
              <p className="report-headline">{selected.headline}</p>
              <p>{selected.executive_summary}</p>
            </CardBody>
          </Card>

          {selected.product_health && (
            <StatGrid>
              <Stat
                label="Health score"
                value={`${selected.product_health.health_score}/100`}
                icon="zap"
                featured
              />
              <Stat label="Records analysed" value={selected.product_health.records_analyzed} icon="inbox" />
              <Stat label="Negative share" value={`${selected.product_health.negative_share}%`} icon="alert" />
              <Stat label="Pain points" value={selected.product_health.pain_points_count} icon="target" />
              <Stat label="Feature clusters" value={selected.product_health.clusters_count} icon="layers" />
              <Stat label="Themes" value={selected.product_health.themes_count} icon="tag" />
            </StatGrid>
          )}

          {selected.product_health?.coverage_note && (
            <Alert
              variant={String(selected.product_health.coverage_note).includes('not reflected') ? 'warning' : 'info'}
              title="Data coverage"
            >
              {selected.product_health.coverage_note}
            </Alert>
          )}

          <Section title="Key findings" hint="Each finding names the measured numbers it stands on.">
            <div className="insights-grid">
              {(selected.key_findings || []).map((finding) => (
                <Card key={finding.title}>
                  <CardBody className="stack stack-sm">
                    <div className="row row-between">
                      <h3 className="section-title">{finding.title}</h3>
                      <Badge tone={SEVERITY_TONES[finding.severity] || 'neutral'}>{finding.severity}</Badge>
                    </div>
                    <p className="text-sm">{finding.detail}</p>
                    <p className="text-muted text-xs">
                      {finding.evidence} · {finding.source}
                    </p>
                  </CardBody>
                </Card>
              ))}
            </div>
          </Section>

          <Section title="Strategic pillars" hint="With a roadmap in place, the pillars are the milestones actually planned.">
            <div className="stack stack-md">
              {(selected.strategic_pillars || []).map((pillar) => (
                <Card key={pillar.name}>
                  <CardBody className="stack stack-sm">
                    <h3 className="section-title">{pillar.name}</h3>
                    <p className="text-sm">
                      <strong>Objective:</strong> {pillar.objective}
                    </p>
                    <p className="text-sm">
                      <strong>Why:</strong> {pillar.rationale}
                    </p>
                    {pillar.linked_items?.length > 0 && (
                      <p className="text-muted text-sm">Scope: {pillar.linked_items.join(', ')}</p>
                    )}
                    <p className="text-muted text-xs">{pillar.evidence}</p>
                  </CardBody>
                </Card>
              ))}
            </div>
          </Section>

          {selected.roadmap_outlook?.length > 0 && (
            <Section title="Roadmap outlook" hint="What ships when, from the stored roadmap.">
              <Card>
                <CardBody>
                  <div className="table-responsive">
                    <table className="table">
                      <thead>
                        <tr>
                          <th scope="col">Release</th>
                          <th scope="col">Horizon</th>
                          <th scope="col">Window</th>
                          <th scope="col">Items</th>
                          <th scope="col">Effort</th>
                          <th scope="col">Customers</th>
                        </tr>
                      </thead>
                      <tbody>
                        {selected.roadmap_outlook.map((release) => (
                          <tr key={release.release}>
                            <td>{release.release}</td>
                            <td>{release.horizon}</td>
                            <td>
                              {formatDate(release.start_date)} → {formatDate(release.end_date)}
                            </td>
                            <td>{release.item_count}</td>
                            <td>
                              {release.effort_total}/{release.capacity}
                            </td>
                            <td>{release.customer_records}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </CardBody>
              </Card>
            </Section>
          )}

          <Section title="Product indicators" hint="What this workspace can actually observe.">
            <StatGrid>
              {(selected.kpis || []).map((kpi) => (
                <Stat key={kpi.metric} label={kpi.metric} value={kpi.value} hint={kpi.interpretation} />
              ))}
            </StatGrid>
          </Section>

          <Section title="Risks & recommendations">
            <div className="insights-grid">
              <Card>
                <CardHeader title="Risks" hint="Named from the plan's own weak points." />
                <CardBody className="stack stack-sm">
                  {(selected.risks || []).map((risk) => (
                    <div key={risk.risk} className="stack stack-xs">
                      <div className="row row-between">
                        <strong className="text-sm">{risk.risk}</strong>
                        <Badge tone={SEVERITY_TONES[risk.severity] || 'neutral'}>{risk.severity}</Badge>
                      </div>
                      <p className="text-muted text-sm">{risk.mitigation}</p>
                    </div>
                  ))}
                </CardBody>
              </Card>

              <Card>
                <CardHeader title="Recommendations" hint="In the order the evidence supports them." />
                <CardBody className="stack stack-sm">
                  {(selected.recommendations || []).map((rec) => (
                    <div key={rec.action} className="stack stack-xs">
                      <div className="row row-between">
                        <strong className="text-sm">{rec.action}</strong>
                        <Badge tone="neutral">{rec.horizon}</Badge>
                      </div>
                      <p className="text-muted text-sm">
                        {rec.owner} · {rec.rationale}
                      </p>
                    </div>
                  ))}
                </CardBody>
              </Card>
            </div>
          </Section>

          <Card>
            <CardHeader title="Evidence & method" hint="Where every number in this report came from." />
            <CardBody className="stack stack-sm">
              <div className="evidence-grid">
                <div>
                  <span className="text-muted text-xs">Written by</span>
                  <strong>{selected.evidence?.generated_by}</strong>
                </div>
                <div>
                  <span className="text-muted text-xs">Records analysed</span>
                  <strong>{selected.evidence?.records_analyzed}</strong>
                </div>
                <div>
                  <span className="text-muted text-xs">Records stored</span>
                  <strong>{selected.evidence?.records_stored}</strong>
                </div>
                <div>
                  <span className="text-muted text-xs">Prioritised items</span>
                  <strong>{selected.evidence?.items_planned}</strong>
                </div>
                <div>
                  <span className="text-muted text-xs">Roadmap releases</span>
                  <strong>{selected.evidence?.releases}</strong>
                </div>
                <div>
                  <span className="text-muted text-xs">PRDs / user stories</span>
                  <strong>
                    {selected.evidence?.prds} / {selected.evidence?.user_stories}
                  </strong>
                </div>
              </div>
              <p className="text-muted text-sm">{selected.evidence?.method}</p>
              <p className="text-muted text-xs">
                Generated {formatDate(selected.created_at)} · updated {formatDate(selected.updated_at)}
              </p>
            </CardBody>
          </Card>
        </>
      )}

      <Section
        title="Output quality evaluation"
        hint="Checks every artefact in this workspace for completeness, evidence grounding, freshness and internal consistency."
        actions={
          <Button variant="secondary" icon="checkCircle" onClick={evaluate} disabled={!workspaceId || evaluating}>
            {quality ? 'Re-evaluate' : 'Evaluate output quality'}
          </Button>
        }
      >
        {!quality && (
          <Card>
            <CardBody>
              <p className="text-muted text-sm">
                Run the evaluation to see how the generated insights, backlog, roadmap, PRDs, user stories and
                reports hold up — including whether every number in them can be traced back to measured data.
              </p>
            </CardBody>
          </Card>
        )}

        {quality && (
          <div className="stack stack-md">
            <Alert
              variant={['excellent', 'good'].includes(quality.grade) ? 'success' : quality.grade === 'fair' ? 'warning' : 'danger'}
              title={`Overall ${quality.overall_score}/100 — ${quality.grade.replace(/_/g, ' ')}`}
            >
              {quality.summary}
            </Alert>

            <div className="insights-grid">
              {quality.artifacts.map((artifact) => (
                <Card key={artifact.artifact_type}>
                  <CardHeader
                    title={artifact.label}
                    hint={artifact.available ? `${artifact.passed} passed · ${artifact.warned} warned · ${artifact.failed} failed` : 'Not generated yet'}
                    actions={
                      <Badge tone={GRADE_TONES[artifact.grade] || 'neutral'}>
                        {artifact.available ? `${artifact.score}/100` : artifact.grade.replace(/_/g, ' ')}
                      </Badge>
                    }
                  />
                  <CardBody className="stack stack-sm">
                    {artifact.checks.map((check) => (
                      <div key={check.id} className="stack stack-xs">
                        <div className="row row-between">
                          <span className="text-sm">{check.name}</span>
                          <Badge tone={CHECK_TONES[check.status] || 'neutral'}>{check.status}</Badge>
                        </div>
                        <p className="text-muted text-xs">{check.detail}</p>
                        {(check.evidence || []).map((item) => (
                          <code key={item} className="text-xs text-muted">
                            {item}
                          </code>
                        ))}
                      </div>
                    ))}
                    {artifact.notes?.map((note) => (
                      <p key={note} className="text-muted text-xs">
                        {note}
                      </p>
                    ))}
                  </CardBody>
                </Card>
              ))}
            </div>

            <div className="row row-wrap">
              <Button
                variant="secondary"
                icon="download"
                onClick={() =>
                  downloadMarkdown(`/quality/${workspaceId}/export`, 'output-quality-evaluation.md', () =>
                    setNotice('Quality evaluation exported as Markdown.')
                  )
                }
              >
                Export evaluation
              </Button>
            </div>
          </div>
        )}
      </Section>
    </div>
  );
}
